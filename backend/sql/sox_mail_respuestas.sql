-- =====================================================================
-- SOX Dashboard - Códigos de correo y respuestas de aprobación
--
-- Ejecutar DESPUÉS de sox_mail_outbox.sql, sox_mail_outbox_c5.sql y
-- sox_mail_outbox_c7.sql, una sola vez, con el propietario del esquema AUTOM.
--
-- Código de correo: <código del control>-<serie>[.<reenvío>]
--   001-1     primer correo del Control 1 en el período (año / semestre)
--   001-1.1   reenvío en el MISMO período (misma serie)
--   001-2     primer correo de un período distinto (otro año o campaña)
-- El código va en el asunto: "... [SOX 001-1]". Al responder, el asunto
-- conserva el código y la plataforma asocia la respuesta al correo.
--
-- ESTADO_RESPUESTA:
--   PENDIENTE   enviado, sin respuesta.
--   RESPONDIDO  hay respuesta, pero no dice "OK" (o la envió alguien que no
--               era destinatario): un administrador la revisa y aprueba.
--   APROBADO    respuesta "OK" de un destinatario, o aprobación manual.
-- =====================================================================

ALTER TABLE AUTOM.SOX_MAIL_OUTBOX ADD (
    CODIGO            VARCHAR2(20),
    CODIGO_SERIE      NUMBER(6),
    CODIGO_REENVIO    NUMBER(4),
    ESTADO_RESPUESTA  VARCHAR2(20),
    FECHA_RESPUESTA   TIMESTAMP
);

ALTER TABLE AUTOM.SOX_MAIL_OUTBOX ADD CONSTRAINT SOX_MAIL_OUTBOX_COD_UK UNIQUE (CODIGO);

ALTER TABLE AUTOM.SOX_MAIL_OUTBOX ADD CONSTRAINT SOX_MAIL_OUTBOX_RESP_CK CHECK
    (ESTADO_RESPUESTA IS NULL OR ESTADO_RESPUESTA IN ('PENDIENTE','RESPONDIDO','APROBADO'));

CREATE INDEX AUTOM.SOX_MAIL_OUTBOX_SERIE_IX
    ON AUTOM.SOX_MAIL_OUTBOX (CONTROL_NUMERO, CODIGO_SERIE);

CREATE TABLE AUTOM.SOX_MAIL_RESPUESTAS (
    ID                   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OUTBOX_ID            NUMBER         NOT NULL,
    GRAPH_MESSAGE_ID     VARCHAR2(500)  NOT NULL,
    INTERNET_MESSAGE_ID  VARCHAR2(500),
    REMITENTE            VARCHAR2(254),
    ASUNTO               VARCHAR2(255),
    FECHA_RECIBIDO       TIMESTAMP,
    EXTRACTO             VARCHAR2(1000),
    APRUEBA              NUMBER(1)      DEFAULT 0 NOT NULL,
    EVIDENCIA_ID         NUMBER,
    REGISTRADO_EN        TIMESTAMP      NOT NULL,
    CONSTRAINT SOX_MAIL_RESP_GRAPH_UK UNIQUE (GRAPH_MESSAGE_ID),
    CONSTRAINT SOX_MAIL_RESP_APR_CK CHECK (APRUEBA IN (0, 1)),
    CONSTRAINT SOX_MAIL_RESP_OUT_FK FOREIGN KEY (OUTBOX_ID)
        REFERENCES AUTOM.SOX_MAIL_OUTBOX (ID),
    CONSTRAINT SOX_MAIL_RESP_EVI_FK FOREIGN KEY (EVIDENCIA_ID)
        REFERENCES AUTOM.SOX_CONTROL_EVIDENCIAS (ID)
);

CREATE INDEX AUTOM.SOX_MAIL_RESP_OUT_IX ON AUTOM.SOX_MAIL_RESPUESTAS (OUTBOX_ID);
CREATE INDEX AUTOM.SOX_MAIL_RESP_EVI_IX ON AUTOM.SOX_MAIL_RESPUESTAS (EVIDENCIA_ID);

COMMENT ON TABLE AUTOM.SOX_MAIL_RESPUESTAS IS
  'Respuestas recibidas a correos SOX con código; cada una se archiva como evidencia';

