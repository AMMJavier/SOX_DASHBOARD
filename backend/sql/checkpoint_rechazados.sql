-- Estado de los objetos (deben salir VALID / ENABLED):
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS FROM ALL_OBJECTS
 WHERE OWNER = 'AUTOM' AND OBJECT_NAME IN ('CHECKPOINT_RECHAZADOS', 'F_CHECKPOINT_MOTIVO', 'TRG_FUENTE_CHECKPOINT_TRANSFORM');

-- Debe coincidir con la diferencia del dashboard (p. ej. 769 - 763 = 6):
SELECT (SELECT COUNT(*) FROM AUTOM.FUENTE_CHECKPOINT)     AS FUENTE,
       (SELECT COUNT(*) FROM AUTOM.CHECKPOINT_TRANSFORM)  AS TRANSFORM,
       (SELECT COUNT(*) FROM AUTOM.CHECKPOINT_RECHAZADOS) AS RECHAZADOS
  FROM DUAL;

