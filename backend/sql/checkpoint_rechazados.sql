-- =====================================================================
-- SOX Control 7 - VPN de Check Point que NO cumplen el formato del comentario
--
-- Formato válido del comentario (regla del trigger TRG_FUENTE_CHECKPOINT_TRANSFORM):
--     REQ - SOLICITANTE - GERENTE
--   * exactamente dos separadores " - " (espacio, guion, espacio) => 3 partes
--   * ninguna parte vacía
--   * REQ hasta 50 caracteres; solicitante y gerente hasta 200
--
-- Este script:
--   1. Crea AUTOM.CHECKPOINT_RECHAZADOS (VPN rechazadas, con el motivo exacto).
--   2. Crea AUTOM.F_CHECKPOINT_MOTIVO: devuelve NULL si el comentario es válido
--      o el motivo del rechazo. Es la ÚNICA definición de la regla.
--   3. Reemplaza el trigger: las VPN válidas siguen igual a CHECKPOINT_TRANSFORM;
--      las inválidas se registran en CHECKPOINT_RECHAZADOS (antes se descartaban
--      en silencio). Si una VPN se corrige en Check Point, sale de rechazados.
--   4. Registra las VPN rechazadas que ya existen hoy (carga inicial).
--
-- También corrige un riesgo: un REQ de más de 50 caracteres (o solicitante/gerente
-- de más de 200) hacía fallar el trigger y CANCELABA la sincronización completa.
-- Ahora esa VPN queda rechazada con su motivo y la sincronización continúa.
--
-- Al cerrar la campaña NO se vacía esta tabla: queda el historial por campaña.
--
-- Ejecutar UNA vez con el propietario de AUTOM (sqlplus):
--     @checkpoint_rechazados.sql
-- Para volver atrás: @respaldo_trg_fuente_checkpoint_transform.sql
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. Tabla
-- ---------------------------------------------------------------------
CREATE TABLE AUTOM.CHECKPOINT_RECHAZADOS (
    ID                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CAMPANA        NUMBER,                   -- campaña activa al detectarla (NULL si no había)
    CHECKPOINT_UID    VARCHAR2(100)  NOT NULL,
    NOMBRE_VPN        VARCHAR2(255),
    COMENTARIO        VARCHAR2(4000),           -- comentario original de Check Point
    MOTIVO            VARCHAR2(200)  NOT NULL,
    FECHA_ALMACENADO  TIMESTAMP,                -- fecha de extracción en FUENTE_CHECKPOINT
    FECHA_DETECCION   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- Una fila por VPN y campaña (NVL para que también aplique cuando no hay campaña activa).
CREATE UNIQUE INDEX AUTOM.CHECKPOINT_RECH_UK
    ON AUTOM.CHECKPOINT_RECHAZADOS (NVL(ID_CAMPANA, 0), CHECKPOINT_UID);

COMMENT ON TABLE AUTOM.CHECKPOINT_RECHAZADOS IS
  'VPN de Check Point cuyo comentario no cumple REQ - SOLICITANTE - GERENTE; no entran a la validación de gerentes';

-- ---------------------------------------------------------------------
-- 2. Función con la regla del comentario
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION AUTOM.F_CHECKPOINT_MOTIVO (p_comentario IN VARCHAR2)
RETURN VARCHAR2
DETERMINISTIC
IS
    v_pos1   PLS_INTEGER;
    v_pos2   PLS_INTEGER;
    v_pos3   PLS_INTEGER;
    v_req    VARCHAR2(4000);
    v_sol    VARCHAR2(4000);
    v_ger    VARCHAR2(4000);
    v_faltan VARCHAR2(100);
BEGIN
    IF TRIM(p_comentario) IS NULL THEN
        RETURN 'Comentario vacío';
    END IF;

    v_pos1 := INSTR(p_comentario, ' - ', 1, 1);
    v_pos2 := INSTR(p_comentario, ' - ', 1, 2);
    v_pos3 := INSTR(p_comentario, ' - ', 1, 3);

    IF v_pos1 = 0 THEN
        RETURN 'Sin separador " - " (formato: REQ - SOLICITANTE - GERENTE)';
    ELSIF v_pos2 = 0 THEN
        RETURN 'Solo 2 partes: falta una (formato: REQ - SOLICITANTE - GERENTE)';
    ELSIF v_pos3 > 0 THEN
        RETURN 'Más de 3 partes: el separador " - " aparece más de dos veces';
    END IF;

    v_req := TRIM(SUBSTR(p_comentario, 1, v_pos1 - 1));
    v_sol := TRIM(SUBSTR(p_comentario, v_pos1 + 3, v_pos2 - (v_pos1 + 3)));
    v_ger := TRIM(SUBSTR(p_comentario, v_pos2 + 3));

    IF v_req IS NULL THEN v_faltan := 'REQ'; END IF;
    IF v_sol IS NULL THEN v_faltan := v_faltan || CASE WHEN v_faltan IS NOT NULL THEN ', ' END || 'solicitante'; END IF;
    IF v_ger IS NULL THEN v_faltan := v_faltan || CASE WHEN v_faltan IS NOT NULL THEN ', ' END || 'gerente'; END IF;
    IF v_faltan IS NOT NULL THEN
        RETURN 'Falta ' || v_faltan;
    END IF;

    IF LENGTH(v_req) > 50 THEN RETURN 'REQ supera 50 caracteres'; END IF;
    IF LENGTH(v_sol) > 200 THEN RETURN 'Solicitante supera 200 caracteres'; END IF;
    IF LENGTH(v_ger) > 200 THEN RETURN 'Gerente supera 200 caracteres'; END IF;

    RETURN NULL;  -- comentario válido
END;
/

-- ---------------------------------------------------------------------
-- 3. Trigger (reemplaza al original; respaldo en respaldo_trg_fuente_checkpoint_transform.sql)
-- ---------------------------------------------------------------------
CREATE OR REPLACE TRIGGER AUTOM.TRG_FUENTE_CHECKPOINT_TRANSFORM
AFTER INSERT OR UPDATE ON AUTOM.FUENTE_CHECKPOINT
FOR EACH ROW
DECLARE
    v_motivo      VARCHAR2(200);
    v_campana     NUMBER;
    v_pos1        PLS_INTEGER;
    v_pos2        PLS_INTEGER;
    v_req         VARCHAR2(50);
    v_solicitante VARCHAR2(200);
    v_gerente     VARCHAR2(200);
BEGIN
    v_motivo := AUTOM.F_CHECKPOINT_MOTIVO(:NEW.COMENTARIO);

    IF v_motivo IS NULL THEN
        -- Comentario válido: mismo comportamiento que el trigger original.
        v_pos1 := INSTR(:NEW.COMENTARIO, ' - ', 1, 1);
        v_pos2 := INSTR(:NEW.COMENTARIO, ' - ', 1, 2);
        v_req         := TRIM(SUBSTR(:NEW.COMENTARIO, 1, v_pos1 - 1));
        v_solicitante := TRIM(SUBSTR(:NEW.COMENTARIO, v_pos1 + 3, v_pos2 - (v_pos1 + 3)));
        v_gerente     := TRIM(SUBSTR(:NEW.COMENTARIO, v_pos2 + 3));

        MERGE INTO AUTOM.CHECKPOINT_TRANSFORM T
        USING (
            SELECT :NEW.CHECKPOINT_UID AS CHECKPOINT_UID, v_req AS REQ, v_solicitante AS SOLICITANTE,
                   v_gerente AS GERENTE, :NEW.COLOR AS COLOR, :NEW.FECHA_ALMACENADO AS FECHA_ALMACENADO,
                   :NEW.NOMBRE_VPN AS NOMBRE_VPN
              FROM DUAL
        ) S
        ON (T.CHECKPOINT_UID = S.CHECKPOINT_UID)
        WHEN MATCHED THEN UPDATE SET
            T.REQ = S.REQ, T.SOLICITANTE = S.SOLICITANTE, T.GERENTE = S.GERENTE,
            T.COLOR = S.COLOR, T.FECHA_ALMACENADO = S.FECHA_ALMACENADO, T.NOMBRE_VPN = S.NOMBRE_VPN
        WHEN NOT MATCHED THEN
            INSERT (CHECKPOINT_UID, REQ, SOLICITANTE, GERENTE, ESTADO, COLOR,
                    FECHA_ALMACENADO, CONFIRMACION, NOMBRE_VPN)
            VALUES (S.CHECKPOINT_UID, S.REQ, S.SOLICITANTE, S.GERENTE, 'mantener', S.COLOR,
                    S.FECHA_ALMACENADO, 0, S.NOMBRE_VPN);
    END IF;

    -- Registro de rechazadas. Es auxiliar: un error aquí NUNCA debe cancelar la sincronización.
    BEGIN
        SELECT MAX(ID_CAMPANA) INTO v_campana FROM AUTOM.CAMPANAS_SOX WHERE ESTADO = 'ACTIVA';

        IF v_motivo IS NULL THEN
            -- Se corrigió en Check Point: deja de figurar como rechazada en la campaña actual.
            DELETE FROM AUTOM.CHECKPOINT_RECHAZADOS
             WHERE CHECKPOINT_UID = :NEW.CHECKPOINT_UID
               AND (ID_CAMPANA IS NULL OR ID_CAMPANA = v_campana);
        ELSE
            MERGE INTO AUTOM.CHECKPOINT_RECHAZADOS R
            USING (SELECT v_campana AS ID_CAMPANA, :NEW.CHECKPOINT_UID AS CHECKPOINT_UID FROM DUAL) S
            ON (NVL(R.ID_CAMPANA, 0) = NVL(S.ID_CAMPANA, 0) AND R.CHECKPOINT_UID = S.CHECKPOINT_UID)
            WHEN MATCHED THEN UPDATE SET
                R.NOMBRE_VPN = :NEW.NOMBRE_VPN,
                R.COMENTARIO = SUBSTR(:NEW.COMENTARIO, 1, 4000),
                R.MOTIVO = v_motivo,
                R.FECHA_ALMACENADO = :NEW.FECHA_ALMACENADO   -- FECHA_DETECCION conserva la 1ra detección
            WHEN NOT MATCHED THEN
                INSERT (ID_CAMPANA, CHECKPOINT_UID, NOMBRE_VPN, COMENTARIO, MOTIVO, FECHA_ALMACENADO)
                VALUES (v_campana, :NEW.CHECKPOINT_UID, :NEW.NOMBRE_VPN, SUBSTR(:NEW.COMENTARIO, 1, 4000),
                        v_motivo, :NEW.FECHA_ALMACENADO);
        END IF;
    EXCEPTION
        WHEN OTHERS THEN NULL;
    END;
END;
/

ALTER TRIGGER AUTOM.TRG_FUENTE_CHECKPOINT_TRANSFORM ENABLE;

-- ---------------------------------------------------------------------
-- 4. Carga inicial: VPN que hoy están en FUENTE pero no en TRANSFORM
-- ---------------------------------------------------------------------
INSERT INTO AUTOM.CHECKPOINT_RECHAZADOS
    (ID_CAMPANA, CHECKPOINT_UID, NOMBRE_VPN, COMENTARIO, MOTIVO, FECHA_ALMACENADO)
SELECT (SELECT MAX(ID_CAMPANA) FROM AUTOM.CAMPANAS_SOX WHERE ESTADO = 'ACTIVA'),
       f.CHECKPOINT_UID, f.NOMBRE_VPN, SUBSTR(f.COMENTARIO, 1, 4000),
       NVL(AUTOM.F_CHECKPOINT_MOTIVO(f.COMENTARIO), 'No llegó a CHECKPOINT_TRANSFORM'),
       f.FECHA_ALMACENADO
  FROM AUTOM.FUENTE_CHECKPOINT f
 WHERE NOT EXISTS (SELECT 1 FROM AUTOM.CHECKPOINT_TRANSFORM t WHERE t.CHECKPOINT_UID = f.CHECKPOINT_UID)
   AND NOT EXISTS (SELECT 1 FROM AUTOM.CHECKPOINT_RECHAZADOS r WHERE r.CHECKPOINT_UID = f.CHECKPOINT_UID);

COMMIT;

