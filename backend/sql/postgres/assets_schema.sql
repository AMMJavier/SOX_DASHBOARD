-- =====================================================================
--  Assets (inventario de dispositivos) - esquema PostgreSQL
--  Reemplaza AUTOM.INVENTARIO_DISPOSITIVOS / _LOG de Oracle.
--
--  Ejecutar una sola vez con un usuario dueño del esquema:
--      psql -h <host> -U <usuario> -d <base> -f assets_schema.sql
--  Es idempotente: puede volver a ejecutarse sin perder datos.
-- =====================================================================

SET search_path TO public;

-- ---------------------------------------------------------------------
-- Inventario
-- Longitudes alineadas con TEXT_COLUMNS de routes/assets_routes/upload.py
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS inventario_dispositivos (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    especialidad     VARCHAR(50),
    plataforma       VARCHAR(50),
    tipo             VARCHAR(50),
    dispositivo      VARCHAR(100),
    estado           VARCHAR(30),
    criticidad       VARCHAR(20),
    infraestructura  VARCHAR(30),
    ip               VARCHAR(255),
    mask             VARCHAR(15),
    gateway          VARCHAR(15),
    mac              VARCHAR(17),
    localidad        VARCHAR(100),
    piso             VARCHAR(20),
    lado             VARCHAR(20),
    ciudad           VARCHAR(100),
    so               VARCHAR(255),
    version          VARCHAR(30),
    firmware         VARCHAR(50),
    fabricante       VARCHAR(100),
    modelo           VARCHAR(50),
    serial           VARCHAR(50),
    licencia         VARCHAR(500),
    -- 2099-12-31 = EOS sin definir (EOS_SIN_DEFINIR en el backend)
    eos              DATE NOT NULL DEFAULT DATE '2099-12-31',
    comentario       VARCHAR(500)
);

-- Búsqueda de identidad (fabricante + serial) usada en cargas y ediciones.
CREATE INDEX IF NOT EXISTS ix_inv_disp_identidad
    ON inventario_dispositivos (UPPER(TRIM(fabricante)), UPPER(TRIM(serial)));
CREATE INDEX IF NOT EXISTS ix_inv_disp_ciudad
    ON inventario_dispositivos (UPPER(TRIM(ciudad)));
CREATE INDEX IF NOT EXISTS ix_inv_disp_eos
    ON inventario_dispositivos (eos);

-- ---------------------------------------------------------------------
-- Historial de cambios (una fila por campo modificado)
-- Sin FK a propósito: el historial debe sobrevivir al borrado del activo.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS inventario_dispositivos_log (
    log_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dispositivo_id    BIGINT NOT NULL,
    fecha_cambio      TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
    usuario           VARCHAR(100),
    operacion         VARCHAR(10) NOT NULL,
    campo_modificado  VARCHAR(50),
    valor_anterior    TEXT,
    valor_nuevo       TEXT,
    origen            VARCHAR(100)
);

CREATE INDEX IF NOT EXISTS ix_inv_log_dispositivo
    ON inventario_dispositivos_log (dispositivo_id, fecha_cambio DESC);
CREATE INDEX IF NOT EXISTS ix_inv_log_fecha
    ON inventario_dispositivos_log (fecha_cambio DESC, log_id DESC);

-- ---------------------------------------------------------------------
-- Trigger de auditoría
-- El backend informa usuario/origen con set_config('app.usuario'|'app.origen')
-- (ver assets_database.set_audit_context). Si no se informan, se usa el
-- usuario de base de datos y el origen 'SQL'.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_inventario_dispositivos_audit()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_usuario  VARCHAR(100) := COALESCE(NULLIF(current_setting('app.usuario', true), ''), session_user);
    v_origen   VARCHAR(100) := COALESCE(NULLIF(current_setting('app.origen', true), ''), 'SQL');
    v_old      JSONB;
    v_new      JSONB;
    v_campo    TEXT;
BEGIN
    IF TG_OP = 'INSERT' THEN
        v_new := to_jsonb(NEW) - 'id';
        INSERT INTO inventario_dispositivos_log
            (dispositivo_id, usuario, operacion, campo_modificado, valor_anterior, valor_nuevo, origen)
        SELECT NEW.id, v_usuario, 'INSERT', key, NULL, value, v_origen
        FROM jsonb_each_text(v_new)
        WHERE value IS NOT NULL;
        RETURN NEW;

    ELSIF TG_OP = 'UPDATE' THEN
        v_old := to_jsonb(OLD) - 'id';
        v_new := to_jsonb(NEW) - 'id';
        FOR v_campo IN SELECT jsonb_object_keys(v_new) LOOP
            IF (v_old ->> v_campo) IS DISTINCT FROM (v_new ->> v_campo) THEN
                INSERT INTO inventario_dispositivos_log
                    (dispositivo_id, usuario, operacion, campo_modificado, valor_anterior, valor_nuevo, origen)
                VALUES
                    (NEW.id, v_usuario, 'UPDATE', v_campo, v_old ->> v_campo, v_new ->> v_campo, v_origen);
            END IF;
        END LOOP;
        RETURN NEW;

    ELSE -- DELETE
        INSERT INTO inventario_dispositivos_log
            (dispositivo_id, usuario, operacion, campo_modificado, valor_anterior, valor_nuevo, origen)
        VALUES
            (OLD.id, v_usuario, 'DELETE', 'registro',
             COALESCE(OLD.dispositivo, '') || ' / ' || COALESCE(OLD.serial, ''), NULL, v_origen);
        RETURN OLD;
    END IF;
END;
$$;

DROP TRIGGER IF EXISTS trg_inventario_dispositivos_audit ON inventario_dispositivos;
CREATE TRIGGER trg_inventario_dispositivos_audit
    AFTER INSERT OR UPDATE OR DELETE ON inventario_dispositivos
    FOR EACH ROW EXECUTE FUNCTION fn_inventario_dispositivos_audit();
