-- =====================================================================
-- SOX Dashboard - Bandeja de envíos de correo corporativo (Microsoft Graph)
--
-- Registra cada correo formal enviado desde SOX y su archivado como
-- evidencia. NO duplica contactos ni documentos: los archivos (EML/PDF)
-- se guardan en SOX_EVIDENCE_DIR y en AUTOM.SOX_CONTROL_EVIDENCIAS;
-- aquí solo se guarda la relación y el resultado de cada etapa.
--
-- Estados:
--   PENDIENTE   Solicitud registrada; Graph aún no confirma el envío.
--               (Si queda así tras un timeout, CONFIRMAR en el buzón antes
--               de volver a enviar.)
--   ACEPTADO    Graph aceptó el envío; falta archivar la copia.
--   ARCHIVANDO  Archivado en curso (bloqueo para evitar evidencias dobles).
--   ARCHIVADO   Copia EML + PDF guardadas como evidencia del control.
--   FALLIDO     Graph rechazó el envío. No se reintenta automáticamente.
--
-- Ejecutar una sola vez con el usuario propietario del esquema AUTOM.
-- =====================================================================

CREATE TABLE AUTOM.SOX_MAIL_OUTBOX (
    ID                   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CONTROL_NUMERO       NUMBER(3)      NOT NULL,
    ANIO                 NUMBER(4)      NOT NULL,
    SEMESTRE             NUMBER(1),
    TIPO_EVIDENCIA       VARCHAR2(40)   NOT NULL,
    ORIGEN               VARCHAR2(20)   DEFAULT 'MANUAL' NOT NULL,
    IDEMPOTENCY_KEY      VARCHAR2(64)   NOT NULL,
    CORRELACION          VARCHAR2(32)   NOT NULL,
    EMISOR               VARCHAR2(254)  NOT NULL,
    DESTINATARIOS        VARCHAR2(2000) NOT NULL,
    CC                   VARCHAR2(2000),
    ASUNTO               VARCHAR2(255)  NOT NULL,
    CUERPO               CLOB           NOT NULL,
    ADJUNTOS             VARCHAR2(2000),
    ESTADO               VARCHAR2(20)   DEFAULT 'PENDIENTE' NOT NULL,
    DETALLE              VARCHAR2(500),
    INTERNET_MESSAGE_ID  VARCHAR2(500),
    GRAPH_MESSAGE_ID     VARCHAR2(500),
    EVIDENCIA_EML_ID     NUMBER,
    EVIDENCIA_PDF_ID     NUMBER,
    INTENTOS_ARCHIVO     NUMBER(3)      DEFAULT 0 NOT NULL,
    SOLICITADO_POR       NUMBER         NOT NULL,
    FECHA_SOLICITUD      TIMESTAMP      NOT NULL,
    FECHA_ENVIO          TIMESTAMP,
    FECHA_ULTIMO_INTENTO TIMESTAMP,
    FECHA_ARCHIVO        TIMESTAMP,
    CONSTRAINT SOX_MAIL_OUTBOX_IDEM_UK UNIQUE (IDEMPOTENCY_KEY),
    CONSTRAINT SOX_MAIL_OUTBOX_CORR_UK UNIQUE (CORRELACION),
    CONSTRAINT SOX_MAIL_OUTBOX_EST_CK CHECK
        (ESTADO IN ('PENDIENTE','ACEPTADO','ARCHIVANDO','ARCHIVADO','FALLIDO')),
    CONSTRAINT SOX_MAIL_OUTBOX_ORI_CK CHECK
        (ORIGEN IN ('MANUAL','RECORDATORIO','CAMPANA')),
    CONSTRAINT SOX_MAIL_OUTBOX_USR_FK FOREIGN KEY (SOLICITADO_POR)
        REFERENCES AUTOM.USUARIOS (ID),
    CONSTRAINT SOX_MAIL_OUTBOX_EML_FK FOREIGN KEY (EVIDENCIA_EML_ID)
        REFERENCES AUTOM.SOX_CONTROL_EVIDENCIAS (ID),
    CONSTRAINT SOX_MAIL_OUTBOX_PDF_FK FOREIGN KEY (EVIDENCIA_PDF_ID)
        REFERENCES AUTOM.SOX_CONTROL_EVIDENCIAS (ID)
);

CREATE INDEX AUTOM.SOX_MAIL_OUTBOX_CTRL_IX
    ON AUTOM.SOX_MAIL_OUTBOX (CONTROL_NUMERO, ANIO, SEMESTRE);

COMMENT ON TABLE AUTOM.SOX_MAIL_OUTBOX IS
  'Correos formales enviados desde SOX vía Microsoft Graph y su archivado como evidencia';

