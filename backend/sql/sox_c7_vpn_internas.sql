-- =====================================================================
-- SOX Dashboard - Control 7: validación de VPN INTERNAS (LDAP RDP / APLICACIONES)
--
-- Ejecutar una sola vez con el propietario del esquema AUTOM.
--
-- Misma campaña semestral que las VPN externas (AUTOM.CAMPANAS_SOX): al iniciar
-- la campaña se toma una foto de los grupos LDAP RDP y APLICACIONES (los mismos
-- del Control 6) con el jefe ("manager" de Active Directory) de cada cuenta.
-- Cada gerente confirma las cuentas que tiene a cargo: Mantener, Eliminar,
-- No pertenece u Otro (con observación). Las filas quedan por campaña: no se
-- borran al cerrar, así el histórico es la misma tabla filtrada por ID_CAMPANA.
-- =====================================================================

CREATE TABLE AUTOM.SOX_C7_VPN_INTERNAS (
    ID                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CAMPANA          NUMBER         NOT NULL,
    USUARIO             VARCHAR2(100)  NOT NULL,
    NOMBRE              VARCHAR2(200),
    TIPO_ACCESO         VARCHAR2(20)   NOT NULL,
    ACTIVO_AD           NUMBER(1),
    GERENTE             VARCHAR2(200),
    GERENTE_USUARIO     VARCHAR2(100),
    GERENTE_CORREO      VARCHAR2(254),
    GERENTE_MANUAL      NUMBER(1)      DEFAULT 0 NOT NULL,  -- 1 = asignado a mano por el administrador
    ESTADO             VARCHAR2(20)   DEFAULT 'mantener' NOT NULL,
    OBSERVACION         VARCHAR2(1000),
    CONFIRMACION        NUMBER(1)      DEFAULT 0 NOT NULL,
    CONFIRMADO_POR      VARCHAR2(100),
    FECHA_MODIFICACION  TIMESTAMP,
    FECHA_CARGA         TIMESTAMP      NOT NULL,
    CONSTRAINT SOX_C7_INT_UK UNIQUE (ID_CAMPANA, USUARIO, TIPO_ACCESO),
    CONSTRAINT SOX_C7_INT_TIPO_CK CHECK (TIPO_ACCESO IN ('RDP', 'APLICACIONES')),
    CONSTRAINT SOX_C7_INT_EST_CK CHECK (ESTADO IN ('mantener', 'eliminar', 'no pertenece', 'otro')),
    CONSTRAINT SOX_C7_INT_CONF_CK CHECK (CONFIRMACION IN (0, 1)),
    CONSTRAINT SOX_C7_INT_MANUAL_CK CHECK (GERENTE_MANUAL IN (0, 1)),
    CONSTRAINT SOX_C7_INT_CAMP_FK FOREIGN KEY (ID_CAMPANA) REFERENCES AUTOM.CAMPANAS_SOX (ID_CAMPANA)
);

CREATE INDEX AUTOM.SOX_C7_INT_GER_IX ON AUTOM.SOX_C7_VPN_INTERNAS (ID_CAMPANA, GERENTE_USUARIO);

CREATE TABLE AUTOM.SOX_C7_VPN_INTERNAS_LOG (
    ID                    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    INTERNA_ID            NUMBER         NOT NULL,
    ID_CAMPANA            NUMBER         NOT NULL,
    CUENTA                VARCHAR2(100)  NOT NULL,
    TIPO_ACCESO           VARCHAR2(20)   NOT NULL,
    GERENTE               VARCHAR2(200),
    ACCION                VARCHAR2(40)   NOT NULL,
    ESTADO_ANTERIOR       VARCHAR2(20),
    ESTADO_NUEVO          VARCHAR2(20),
    OBSERVACION_ANTERIOR  VARCHAR2(1000),
    OBSERVACION_NUEVA     VARCHAR2(1000),
    USUARIO_SOX           VARCHAR2(100)  NOT NULL,
    FECHA                 TIMESTAMP      NOT NULL,
    CONSTRAINT SOX_C7_INT_LOG_FK FOREIGN KEY (INTERNA_ID) REFERENCES AUTOM.SOX_C7_VPN_INTERNAS (ID)
);

CREATE INDEX AUTOM.SOX_C7_INT_LOG_IX ON AUTOM.SOX_C7_VPN_INTERNAS_LOG (ID_CAMPANA, FECHA);

COMMENT ON TABLE AUTOM.SOX_C7_VPN_INTERNAS IS
  'Control 7: cuentas con VPN interna (LDAP RDP/APLICACIONES) por campaña y su confirmación por el gerente';

